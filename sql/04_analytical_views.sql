CREATE OR REPLACE VIEW VW_TOP_ARTISTS_BY_STREAMS AS
SELECT
    DENSE_RANK() OVER (ORDER BY SUM(f.STREAMS) DESC) AS ARTIST_RANK,
    a.ARTIST_ID,
    a.ARTIST_NAME,
    a.PRIMARY_GENRE,
    a.ARTIST_TIER,
    COUNT(f.TRACK_KEY) AS TRACK_COUNT,
    SUM(f.STREAMS) AS TOTAL_STREAMS,
    ROUND(AVG(f.POPULARITY), 2) AS AVG_POPULARITY,
    ROUND(AVG(f.DANCEABILITY), 3) AS AVG_DANCEABILITY,
    ROUND(AVG(f.ENERGY), 3) AS AVG_ENERGY
FROM FACT_TRACK_STREAM f
JOIN DIM_ARTIST a ON f.ARTIST_ID = a.ARTIST_ID
GROUP BY a.ARTIST_ID, a.ARTIST_NAME, a.PRIMARY_GENRE, a.ARTIST_TIER;

CREATE OR REPLACE VIEW VW_YEARLY_AUDIO_TRENDS AS
SELECT
    d.RELEASE_YEAR,
    g.GENRE_NAME,
    COUNT(f.TRACK_KEY) AS TRACK_COUNT,
    SUM(f.STREAMS) AS TOTAL_STREAMS,
    ROUND(AVG(f.POPULARITY), 2) AS AVG_POPULARITY,
    ROUND(AVG(f.DANCEABILITY), 4) AS AVG_DANCEABILITY,
    ROUND(AVG(f.ENERGY), 4) AS AVG_ENERGY,
    ROUND(AVG(f.VALENCE), 4) AS AVG_VALENCE,
    ROUND(AVG(f.ACOUSTICNESS), 4) AS AVG_ACOUSTICNESS,
    ROUND(AVG(f.TEMPO_BPM), 2) AS AVG_TEMPO_BPM,
    ROUND(AVG(f.DURATION_MS) / 60000, 2) AS AVG_DURATION_MIN
FROM FACT_TRACK_STREAM f
JOIN DIM_DATE d ON f.DATE_ID = d.DATE_ID
JOIN DIM_GENRE g ON f.GENRE_ID = g.GENRE_ID
GROUP BY d.RELEASE_YEAR, g.GENRE_NAME;

CREATE OR REPLACE VIEW VW_GENRE_PERFORMANCE AS
SELECT
    g.GENRE_ID,
    g.GENRE_NAME,
    g.GENRE_CATEGORY,
    COUNT(f.TRACK_KEY) AS TRACK_COUNT,
    SUM(f.STREAMS) AS TOTAL_STREAMS,
    ROUND(AVG(f.POPULARITY), 2) AS AVG_POPULARITY,
    ROUND(SUM(CASE WHEN f.EXPLICIT_FLAG = 'Y' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS EXPLICIT_PCT
FROM FACT_TRACK_STREAM f
JOIN DIM_GENRE g ON f.GENRE_ID = g.GENRE_ID
GROUP BY g.GENRE_ID, g.GENRE_NAME, g.GENRE_CATEGORY;
