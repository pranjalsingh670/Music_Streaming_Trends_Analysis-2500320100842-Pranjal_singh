-- 1. TOP 10 ARTISTS BY TOTAL STREAMS (Verification Query)
SELECT
    ARTIST_RANK,
    ARTIST_NAME,
    PRIMARY_GENRE,
    TRACK_COUNT,
    TOTAL_STREAMS,
    ROUND(TOTAL_STREAMS / 1000000, 2) AS TOTAL_STREAMS_M,
    ROUND(AVG_POPULARITY, 2) AS AVG_POPULARITY,
    ROUND(STREAM_SHARE_PCT, 2) AS STREAM_SHARE_PCT
FROM (
    SELECT
        DENSE_RANK() OVER (ORDER BY SUM(f.STREAMS) DESC) AS ARTIST_RANK,
        a.ARTIST_NAME,
        a.PRIMARY_GENRE,
        COUNT(f.TRACK_KEY) AS TRACK_COUNT,
        SUM(f.STREAMS) AS TOTAL_STREAMS,
        AVG(f.POPULARITY) AS AVG_POPULARITY,
        (SUM(f.STREAMS) * 100.0 / SUM(SUM(f.STREAMS)) OVER ()) AS STREAM_SHARE_PCT
    FROM FACT_TRACK_STREAM f
    JOIN DIM_ARTIST a ON f.ARTIST_ID = a.ARTIST_ID
    GROUP BY a.ARTIST_NAME, a.PRIMARY_GENRE
)
WHERE ARTIST_RANK <= 10
ORDER BY ARTIST_RANK;

-- 2. GENRE PERFORMANCE & AUDIO PROFILE SUMMARY
SELECT
    g.GENRE_NAME,
    COUNT(f.TRACK_KEY) AS TOTAL_TRACKS,
    SUM(f.STREAMS) AS TOTAL_STREAMS,
    ROUND(AVG(f.POPULARITY), 2) AS AVG_POPULARITY,
    ROUND(AVG(f.DANCEABILITY), 3) AS AVG_DANCEABILITY,
    ROUND(AVG(f.ENERGY), 3) AS AVG_ENERGY,
    ROUND(AVG(f.VALENCE), 3) AS AVG_VALENCE,
    ROUND(AVG(f.TEMPO_BPM), 1) AS AVG_TEMPO_BPM,
    ROUND(AVG(f.DURATION_MS) / 60000, 2) AS AVG_DURATION_MIN
FROM FACT_TRACK_STREAM f
JOIN DIM_GENRE g ON f.GENRE_ID = g.GENRE_ID
GROUP BY g.GENRE_NAME
ORDER BY TOTAL_STREAMS DESC;

-- 3. YEARLY AUDIO FEATURE TRENDS WITH YoY DELTA (2015-2025)
WITH YEARLY_STATS AS (
    SELECT
        d.RELEASE_YEAR,
        COUNT(f.TRACK_KEY) AS TRACK_COUNT,
        SUM(f.STREAMS) AS TOTAL_STREAMS,
        ROUND(AVG(f.POPULARITY), 2) AS AVG_POPULARITY,
        ROUND(AVG(f.DANCEABILITY), 4) AS AVG_DANCEABILITY,
        ROUND(AVG(f.ENERGY), 4) AS AVG_ENERGY,
        ROUND(AVG(f.VALENCE), 4) AS AVG_VALENCE,
        ROUND(AVG(f.ACOUSTICNESS), 4) AS AVG_ACOUSTICNESS,
        ROUND(AVG(f.DURATION_MS) / 1000, 1) AS AVG_DURATION_SEC
    FROM FACT_TRACK_STREAM f
    JOIN DIM_DATE d ON f.DATE_ID = d.DATE_ID
    WHERE d.IS_IMPUTED_DATE = 'N'
    GROUP BY d.RELEASE_YEAR
)
SELECT
    RELEASE_YEAR,
    TRACK_COUNT,
    TOTAL_STREAMS,
    AVG_POPULARITY,
    AVG_DANCEABILITY,
    ROUND(AVG_DANCEABILITY - LAG(AVG_DANCEABILITY) OVER (ORDER BY RELEASE_YEAR), 4) AS DANCEABILITY_YOY_DIFF,
    AVG_ENERGY,
    AVG_VALENCE,
    AVG_ACOUSTICNESS,
    AVG_DURATION_SEC
FROM YEARLY_STATS
ORDER BY RELEASE_YEAR;

-- 4. AUDIO FEATURE CORRELATION PROXY: POPULARITY QUARTILES (NTILE)
WITH POP_QUARTILES AS (
    SELECT
        TRACK_KEY,
        POPULARITY,
        STREAMS,
        DANCEABILITY,
        ENERGY,
        VALENCE,
        LOUDNESS_DB,
        ACOUSTICNESS,
        NTILE(4) OVER (ORDER BY POPULARITY) AS POP_QUARTILE
    FROM FACT_TRACK_STREAM
)
SELECT
    POP_QUARTILE,
    COUNT(*) AS TRACK_COUNT,
    MIN(POPULARITY) AS MIN_POP,
    MAX(POPULARITY) AS MAX_POP,
    ROUND(AVG(STREAMS) / 1000000, 2) AS AVG_STREAMS_M,
    ROUND(AVG(DANCEABILITY), 3) AS AVG_DANCEABILITY,
    ROUND(AVG(ENERGY), 3) AS AVG_ENERGY,
    ROUND(AVG(VALENCE), 3) AS AVG_VALENCE,
    ROUND(AVG(LOUDNESS_DB), 2) AS AVG_LOUDNESS_DB,
    ROUND(AVG(ACOUSTICNESS), 3) AS AVG_ACOUSTICNESS
FROM POP_QUARTILES
GROUP BY POP_QUARTILE
ORDER BY POP_QUARTILE;
