-- 1. Dimension: Artists
CREATE TABLE DIM_ARTIST (
    ARTIST_ID        NUMBER(10)     PRIMARY KEY,
    ARTIST_NAME      VARCHAR2(200)  NOT NULL,
    PRIMARY_GENRE    VARCHAR2(100),
    ARTIST_TIER      VARCHAR2(30)   CHECK (ARTIST_TIER IN ('Superstar', 'Mainstream', 'Emerging', 'Indie')),
    COUNTRY_REGION   VARCHAR2(60)
);

-- 2. Dimension: Genres
CREATE TABLE DIM_GENRE (
    GENRE_ID         NUMBER(10)     PRIMARY KEY,
    GENRE_NAME       VARCHAR2(100)  NOT NULL UNIQUE,
    GENRE_CATEGORY   VARCHAR2(60)
);

-- 3. Dimension: Release Dates
CREATE TABLE DIM_DATE (
    DATE_ID          NUMBER(8)      PRIMARY KEY, -- YYYYMMDD format
    RELEASE_DATE     DATE           NOT NULL,
    RELEASE_YEAR     NUMBER(4)      NOT NULL,
    RELEASE_QUARTER  NUMBER(1)      CHECK (RELEASE_QUARTER BETWEEN 1 AND 4),
    RELEASE_MONTH    NUMBER(2)      CHECK (RELEASE_MONTH BETWEEN 1 AND 12),
    MONTH_NAME       VARCHAR2(20),
    IS_IMPUTED_DATE  CHAR(1)        DEFAULT 'N' CHECK (IS_IMPUTED_DATE IN ('Y', 'N'))
);

-- 4. Fact Table: Track Streams & Audio Features
CREATE TABLE FACT_TRACK_STREAM (
    TRACK_KEY        NUMBER(12)     PRIMARY KEY,
    TRACK_ID         VARCHAR2(64)   NOT NULL UNIQUE,
    TRACK_NAME       VARCHAR2(300)  NOT NULL,
    ARTIST_ID        NUMBER(10)     NOT NULL,
    GENRE_ID         NUMBER(10)     NOT NULL,
    DATE_ID          NUMBER(8)      NOT NULL,
    STREAMS          NUMBER(15)     DEFAULT 0 CHECK (STREAMS >= 0),
    POPULARITY       NUMBER(5, 2)   CHECK (POPULARITY BETWEEN 0 AND 100),
    EXPLICIT_FLAG    CHAR(1)        DEFAULT 'N' CHECK (EXPLICIT_FLAG IN ('Y', 'N')),
    DURATION_MS      NUMBER(10)     CHECK (DURATION_MS > 0),
    DANCEABILITY     NUMBER(5, 4)   CHECK (DANCEABILITY BETWEEN 0 AND 1),
    ENERGY           NUMBER(5, 4)   CHECK (ENERGY BETWEEN 0 AND 1),
    VALENCE          NUMBER(5, 4)   CHECK (VALENCE BETWEEN 0 AND 1),
    TEMPO_BPM        NUMBER(6, 2)   CHECK (TEMPO_BPM > 0),
    LOUDNESS_DB      NUMBER(6, 2),
    ACOUSTICNESS     NUMBER(5, 4)   CHECK (ACOUSTICNESS BETWEEN 0 AND 1),
    INSTRUMENTALNESS NUMBER(5, 4)   CHECK (INSTRUMENTALNESS BETWEEN 0 AND 1),
    LIVENESS         NUMBER(5, 4)   CHECK (LIVENESS BETWEEN 0 AND 1),
    SPEECHINESS      NUMBER(5, 4)   CHECK (SPEECHINESS BETWEEN 0 AND 1),
    CONSTRAINT FK_FACT_ARTIST FOREIGN KEY (ARTIST_ID) REFERENCES DIM_ARTIST (ARTIST_ID),
    CONSTRAINT FK_FACT_GENRE  FOREIGN KEY (GENRE_ID)  REFERENCES DIM_GENRE (GENRE_ID),
    CONSTRAINT FK_FACT_DATE   FOREIGN KEY (DATE_ID)   REFERENCES DIM_DATE (DATE_ID)
);

-- Performance Indexes for Power BI & Analytical Queries
CREATE INDEX IDX_FACT_ARTIST ON FACT_TRACK_STREAM (ARTIST_ID);
CREATE INDEX IDX_FACT_GENRE  ON FACT_TRACK_STREAM (GENRE_ID);
CREATE INDEX IDX_FACT_DATE   ON FACT_TRACK_STREAM (DATE_ID);
CREATE INDEX IDX_FACT_POP    ON FACT_TRACK_STREAM (POPULARITY);
